"""Inference entry point for replay, prediction, and recognition.

A checkpoint is an input from a training run that you implement in
``cattle4d.engine.train.fit``. This repository does not contain one.
``run`` validates the request and stops before synthesis.
"""

from __future__ import annotations

import argparse
import logging
from pathlib import Path

from cattle4d.config import ExperimentConfig, load_experiment
from cattle4d.data.multiview import load_sequence
from cattle4d.pipeline import Cattle4DPipeline, build_pipeline

logger = logging.getLogger("cattle4d.infer")


def run(
    pipeline: Cattle4DPipeline,
    sequence_dir: Path,
    checkpoint: Path,
    output_dir: Path,
) -> None:
    """Load ``checkpoint`` and write replay, prediction, and recognition.

    Intended outputs, once the body is implemented::

        <output_dir>/<sequence_id>/replay/<camera>/<frame>.png
        <output_dir>/<sequence_id>/prediction/<camera>/<frame>.png
        <output_dir>/<sequence_id>/recognition.json

    The function checks that the sequence parses and that the checkpoint file
    exists, then stops. It does not create those files and it does not read
    the checkpoint, because there is no agreed state-dict layout yet. Define
    that layout next to ``fit``.
    """

    sequence = load_sequence(sequence_dir)
    if not checkpoint.is_file():
        raise FileNotFoundError(
            f"No checkpoint at {checkpoint}. Train one with cattle4d.engine.train "
            "after fit() is implemented. This repository releases no weights."
        )
    raise NotImplementedError(
        "cattle4d.engine.infer.run is the inference entry point. "
        f"Sequence {sequence.sequence_id} has {sequence.num_frames} frames. "
        f"Wire checkpoint {checkpoint} into the pipeline and write results under "
        f"{output_dir / sequence.sequence_id}. No images are generated by this stub."
    )


def main(argv: list[str] | None = None) -> int:
    parser = _parser()
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    experiment = load_experiment(args.config, args.paths)
    pipeline = build_pipeline(experiment.config)
    logger.info("Cattle4DGS inference scaffold")
    logger.info(pipeline.describe())
    if args.dry_run:
        logger.info(
            "Dry run finished. A real run needs --checkpoint from your own training "
            "and --sequence under data_root. No weights are released."
        )
        return 0
    if args.checkpoint is None or args.sequence is None:
        parser.error("--checkpoint and --sequence are required unless --dry-run is set.")
    sequence_dir = _resolve_sequence(experiment, args.sequence)
    output_dir = Path(args.output_dir) if args.output_dir is not None else experiment.output_dir
    run(pipeline, sequence_dir, args.checkpoint, output_dir)
    return 0


def _resolve_sequence(experiment: ExperimentConfig, sequence: str) -> Path:
    candidate = Path(sequence)
    if candidate.is_dir() and (candidate / "cameras.yaml").is_file():
        return candidate
    rooted = experiment.data_root / "sequences" / sequence
    if rooted.is_dir():
        return rooted
    raise FileNotFoundError(
        f"Sequence {sequence} was not found at {candidate} or {rooted}. "
        "Set data_root in configs/path.yaml."
    )


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="python -m cattle4d.engine.infer",
        description=(
            "Replay and predict a cattle gait with a user-trained Cattle4DGS checkpoint. "
            "No checkpoint ships with this repository."
        ),
    )
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--paths", type=Path, required=True)
    parser.add_argument("--checkpoint", type=Path, default=None)
    parser.add_argument(
        "--sequence",
        default=None,
        help="Sequence id under data_root/sequences, or a path to a sequence directory.",
    )
    parser.add_argument("--output-dir", type=Path, default=None)
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print the pipeline contract and exit before loading a checkpoint.",
    )
    return parser


if __name__ == "__main__":
    raise SystemExit(main())
