"""Entry point for turning an MmCows export into Cattle4DGS sequences.

MmCows (Vu et al., NeurIPS 2024 Datasets and Benchmarks) provides synchronized
multi-view barn imagery and behavior labels, including walking. This project
does not redistribute that corpus. The function below is the place to select
walking intervals and write them into the ``sequences/<id>`` layout.

Run ``python -m cattle4d.data.mmcows --help`` for the arguments. The conversion
body is intentionally unimplemented.
"""

from __future__ import annotations

import argparse
from pathlib import Path


def convert_walking_sequences(
    mmcows_root: Path,
    output_root: Path,
    cow_ids: list[str] | None = None,
) -> None:
    """Write walking clips from ``mmcows_root`` into ``output_root``.

    Parameters
    ----------
    mmcows_root :
        Local extract of the MmCows visual data. The published archive layout
        is described by the MmCows authors; this function does not download it.
    output_root :
        Destination that should receive ``sequences/`` and ``splits/``.
    cow_ids :
        Optional subset. ``None`` means the experiment has not chosen a subset.

    The selection of a walking cycle, the mask of the animal, and the export
    of per-view frames all belong to the study protocol. Fill this function
    in before treating MmCows as training input.
    """

    mmcows_root = Path(mmcows_root)
    output_root = Path(output_root)
    if not mmcows_root.exists():
        raise FileNotFoundError(
            f"MmCows root does not exist: {mmcows_root}. "
            "Download the dataset from the authors and set mmcows_root."
        )
    if cow_ids is not None and not cow_ids:
        raise ValueError("cow_ids was empty. Pass ids or leave the filter unset.")
    raise NotImplementedError(
        "convert_walking_sequences is the MmCows adapter entry point. "
        f"Write selected clips from {mmcows_root} into {output_root / 'sequences'} "
        "using the layout in README.md. No clips are generated by this stub."
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m cattle4d.data.mmcows",
        description=(
            "Prepare Cattle4DGS sequences from a local MmCows export. "
            "The conversion is an unimplemented entry point."
        ),
    )
    parser.add_argument("--mmcows-root", type=Path, required=True)
    parser.add_argument("--output-root", type=Path, required=True)
    parser.add_argument(
        "--cow-id",
        action="append",
        dest="cow_ids",
        default=None,
        help="Repeat to keep a subset of animal ids. Omit to leave the filter unset.",
    )
    args = parser.parse_args(argv)
    convert_walking_sequences(args.mmcows_root, args.output_root, args.cow_ids)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
